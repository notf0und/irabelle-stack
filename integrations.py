# --- docker -----------------------------------------------------------------
def docker(*args, check=False):
    return subprocess.run(["docker", *args], capture_output=True, text=True, check=check)


def running(name):
    r = docker("inspect", "-f", "{{.State.Running}}", name)
    return r.returncode == 0 and r.stdout.strip() == "true"


def address(name):
    """The container's address on app-bridge (or its only network)."""
    r = docker("inspect", name)
    if r.returncode != 0:
        return None
    info = json.loads(r.stdout)[0]
    if info["HostConfig"].get("NetworkMode") == "host":
        return "127.0.0.1"  # Plex: on the host network, so this host's localhost
    nets = info["NetworkSettings"]["Networks"]
    if NETWORK in nets and nets[NETWORK].get("IPAddress"):
        return nets[NETWORK]["IPAddress"]
    for n in nets.values():
        if n.get("IPAddress"):
            return n["IPAddress"]
    return None


def compose(stack, *args):
    return subprocess.run(["docker", "compose", *args], cwd=os.path.join(REPO, stack),
                          capture_output=True, text=True)


# --- http -------------------------------------------------------------------
class HttpError(Exception):
    def __init__(self, status, body, url):
        super().__init__(f"HTTP {status} from {url}: {body[:300]}")
        self.status, self.body = status, body


class Api:
    """A JSON API at base, with fixed headers (an API key, usually)."""

    def __init__(self, base, headers=None, timeout=60):
        self.base, self.headers, self.timeout = base.rstrip("/"), dict(headers or {}), timeout
        self.opener = urllib.request.build_opener(
            urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))

    def call(self, method, path, body=None, form=None, headers=None, raw=False):
        url = self.base + path
        hdrs = {"Accept": "application/json", **self.headers, **(headers or {})}
        data = None
        if form is not None:
            data = urllib.parse.urlencode(form, doseq=True).encode()
            hdrs["Content-Type"] = "application/x-www-form-urlencoded"
        elif body is not None:
            data = json.dumps(body).encode()
            hdrs["Content-Type"] = "application/json"
        req = urllib.request.Request(url, data=data, method=method, headers=hdrs)
        try:
            with self.opener.open(req, timeout=self.timeout) as resp:
                text = resp.read().decode("utf-8", "replace")
                if raw:
                    return text
                return json.loads(text) if text.strip() else None
        except urllib.error.HTTPError as e:
            raise HttpError(e.code, e.read().decode("utf-8", "replace"), url) from None

    def get(self, path, **kw):
        return self.call("GET", path, **kw)

    def post(self, path, body=None, **kw):
        return self.call("POST", path, body, **kw)

    def put(self, path, body=None, **kw):
        return self.call("PUT", path, body, **kw)


def wait_for(name, port, path="/", timeout=180, ok=(200, 401, 403)):
    """Wait until the container answers HTTP on port; return its base URL."""
    if not running(name):
        return None
    deadline = time.time() + timeout
    while time.time() < deadline:
        ip = address(name)
        if ip:
            base = f"http://{ip}:{port}"
            try:
                with urllib.request.urlopen(base + path, timeout=5) as r:
                    if r.status in ok:
                        return base
            except urllib.error.HTTPError as e:
                if e.code in ok:
                    return base
            except (urllib.error.URLError, OSError):
                pass
        time.sleep(3)
    warn(f"{name} is running but did not answer on :{port} within {timeout}s — skipped")
    return None


def section(title, needs=()):
    """Decorator: run fn(**bases) under a heading once its containers answer."""
    def wrap(fn):
        def run():
            missing = [n for n, _p, _path in needs if not running(n)]
            if missing:
                return  # stack not deployed here: nothing to wire, nothing to say
            say(title)
            bases = {}
            for name, port, path in needs:
                base = wait_for(name, port, path)
                if not base:
                    return
                bases[name.replace("-", "_")] = base
            try:
                fn(**bases)
            except HttpError as e:
                warn(f"{title}: {e}")
            except Exception as e:  # keep going with the next app
                warn(f"{title}: {type(e).__name__}: {e}")
        run.__name__ = fn.__name__
        STEPS.append(run)
        return run
    return wrap


