# Before Sonarr and Radarr, so a server claimed just now gets its connection
# from them on this same run.
def plex_token():
    prefs = os.path.join(REPO, "plex/config/plex/Library/Application Support/Plex Media Server/Preferences.xml")
    try:
        m = re.search(r'PlexOnlineToken="([^"]+)"', open(prefs).read())
        return m.group(1) if m else ""
    except OSError:
        return ""


@section("Plex", needs=[("plex", 32400, "/identity")])
def plex(plex):
    token = plex_token()
    if not token and sys.stdin.isatty():
        # Claiming ties the server to your Plex account. The code is only valid
        # for four minutes, which is why it is asked for now — with Plex
        # running — and not by setup.sh before you deploy it.
        code = input("    Plex claim code from https://plex.tv/claim (Enter to skip): ").strip()
        if code:
            # The image claims itself at start when PLEX_CLAIM is set.
            set_env("plex", "PLEX_CLAIM", code)
            r = compose("plex", "up", "-d", "--force-recreate", "plex")
            if r.returncode != 0:
                warn(f"could not restart Plex with the claim code: {r.stderr.strip()[:200]}")
            for _ in range(40):
                token = plex_token()
                if token:
                    break
                time.sleep(3)
            # Single-use and expired either way: never leave it lying around.
            set_env("plex", "PLEX_CLAIM", "")
            if token:
                note("claimed to your Plex account")
                wait_for("plex", 32400, "/identity")
            else:
                warn("Plex did not claim itself — the code may have expired; get a new one and re-run")
    if not token:
        note("not claimed — run ./integrations.py with a code from https://plex.tv/claim")
        return
    # Plex is on the host network; from here it is localhost.
    api = Api("http://127.0.0.1:32400", {"X-Plex-Token": token})
    have = {loc["path"] for d in api.get("/library/sections").get("MediaContainer", {}).get("Directory", [])
            for loc in d.get("Location", [])}
    for name, kind, agent, scanner, path in (
            ("Movies", "movie", "tv.plex.agents.movie", "Plex Movie", "/data/downloads/movies"),
            ("TV Shows", "show", "tv.plex.agents.series", "Plex TV Series", "/data/downloads/tv")):
        if path in have:
            note(f"library {name} exists")
            continue
        q = urllib.parse.urlencode({"name": name, "type": kind, "agent": agent, "scanner": scanner,
                                    "language": "en-US", "location": path})
        api.call("POST", "/library/sections?" + q, raw=True)
        note(f"library {name}: {path}")
    # Plex only turns a queued library update into a real scan when one of its
    # own scan settings is on. With both off, the connection Sonarr and Radarr
    # get below is accepted and then dropped, so new imports show up only after
    # a manual "Scan Library Files" — turn automatic and hourly scanning on.
    prefs = urllib.parse.urlencode({
        "FSEventLibraryUpdatesEnabled": 1,
        "FSEventLibraryPartialScanEnabled": 1,
        "ScheduledLibraryUpdatesEnabled": 1,
        "ScheduledLibraryUpdateInterval": 3600,
    })
    api.call("PUT", "/:/prefs?" + prefs, raw=True)
    note("library scanning: on file changes (partial) and hourly")


# --- Sonarr and Radarr ------------------------------------------------------
def wire_arr(api, kind):
    tv = kind == "sonarr"
    library = "/data/downloads/tv" if tv else "/data/downloads/movies"
    drop = "/data/downloads/torrents/tv" if tv else "/data/downloads/torrents/movies"

    if not any(r["path"].rstrip("/") == library for r in api.get("/rootfolder")):
        api.post("/rootfolder", {"path": library})
        note(f"root folder {library}")
    else:
        note(f"root folder {library} exists")

    # "Unmonitor Deleted Episodes" / "Unmonitor Deleted Movies": deleting
    # something from Plex removes the file, the next disk scan sees it is gone
    # and the app stops monitoring it, instead of searching for it and pulling
    # it back down.
    media = api.get("/config/mediamanagement")
    flag = "autoUnmonitorPreviouslyDownloadedEpisodes" if tv else "autoUnmonitorPreviouslyDownloadedMovies"
    if not media.get(flag):
        media[flag] = True
        api.put("/config/mediamanagement", media)
        note("unmonitor deleted: on (a Plex delete is not downloaded again)")
    else:
        note("unmonitor deleted already on")

    # The built-in "HD - 720p/1080p" profile is what everything is added with,
    # and Remux-1080p is switched off in it: a 1080p remux is several times the
    # size of a Bluray/WEB 1080p and is not wanted here. Setting the profile on
    # the import lists is what makes it the default for automatically added
    # media (there is no server-wide "default profile" setting in the apps).
    profile = next((p for p in api.get("/qualityprofile") if p["name"] == "HD - 720p/1080p"), None)
    if profile is None:
        note('quality profile "HD - 720p/1080p" missing — profiles left alone')
    else:
        remuxes = [q for q in quality_leaves(profile["items"])
                   if "1080" in q["quality"]["name"] and "remux" in q["quality"]["name"].lower()]
        if any(q["allowed"] for q in remuxes):
            for q in remuxes:
                q["allowed"] = False
            api.put(f"/qualityprofile/{profile['id']}", profile)
            note(f'quality profile {profile["name"]}: Remux-1080p off')
        else:
            note(f'quality profile {profile["name"]}: Remux-1080p already off')
        for il in api.get("/importlist"):
            if il.get("qualityProfileId") != profile["id"]:
                il["qualityProfileId"] = profile["id"]
                api.put(f"/importlist/{il['id']}", il)
                note(f'import list {il["name"]}: quality profile -> {profile["name"]}')

    if not any(c["implementation"] == "Transmission" for c in api.get("/downloadclient")):
        schema = next(s for s in api.get("/downloadclient/schema") if s["implementation"] == "Transmission")
        # A directory, not a category. Transmission has labels of its own, but
        # Sonarr and Radarr refuse a Category and a Directory at the same time,
        # and the directory is what keeps TV and movies in separate drop folders.
        client = fill(schema, host="transmission", port=9091, urlBase="/transmission/",
                      **({"tvDirectory": drop, "tvCategory": ""} if tv
                         else {"movieDirectory": drop, "movieCategory": ""}))
        client.update(name="Transmission", enable=True, priority=1,
                      removeCompletedDownloads=True, removeFailedDownloads=True)
        api.post("/downloadclient", client)
        note(f"download client: Transmission, into {drop}")
    else:
        note("download client Transmission exists")

    token = plex_token()
    if not token:
        note("Plex not claimed yet — no Plex connection (added once it is)")
    elif not any(n["implementation"] == "PlexServer" for n in api.get("/notification")):
        schema = next(s for s in api.get("/notification/schema") if s["implementation"] == "PlexServer")
        conn = fill(schema, host="plex", port=32400, useSsl=False, authToken=token, updateLibrary=True)
        conn["name"] = "Plex"
        for k in list(conn):
            # Every "on <event>" this app supports: imports, upgrades, renames, deletes.
            if k.startswith("on") and isinstance(conn[k], bool) and conn.get("supports" + k[0].upper() + k[1:], True):
                conn[k] = True
        # forceSave: saving tests the connection, and Plex may still be starting.
        api.post("/notification?forceSave=true", conn)
        note("connection: Plex (library updates on import)")
    else:
        note("Plex connection exists")


