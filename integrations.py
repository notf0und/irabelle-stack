@section("Prowlarr", needs=[("prowlarr", 9696, "/ping")])
def prowlarr(prowlarr):
    api = Api(prowlarr + "/api/v1", {"X-Api-Key": ARR["PROWLARR_API_KEY"]})

    tags = {t["label"]: t["id"] for t in api.get("/tag")}
    if "byparr" not in tags:
        tags["byparr"] = api.post("/tag", {"label": "byparr"})["id"]
    byparr_tag = tags["byparr"]

    if not any(p["implementation"] == "FlareSolverr" for p in api.get("/indexerProxy")):
        schema = next(s for s in api.get("/indexerProxy/schema") if s["implementation"] == "FlareSolverr")
        proxy = fill(schema, host="http://byparr:8191/", requestTimeout=180)
        proxy.update(name="Byparr", tags=[byparr_tag])
        api.post("/indexerProxy?forceSave=true", proxy)
        note("indexer proxy: Byparr (for indexers tagged byparr)")
    else:
        note("Byparr proxy exists")

    apps = {a["implementation"] for a in api.get("/applications")}
    for impl, port, key in (("Sonarr", 8989, "SONARR_API_KEY"), ("Radarr", 7878, "RADARR_API_KEY")):
        if impl in apps:
            note(f"app {impl} exists")
            continue
        schema = next(s for s in api.get("/applications/schema") if s["implementation"] == impl)
        app = fill(schema, prowlarrUrl="http://prowlarr:9696",
                   baseUrl=f"http://{impl.lower()}:{port}", apiKey=ARR[key])
        app.update(name=impl, syncLevel="fullSync", enable=True)
        api.post("/applications?forceSave=true", app)
        note(f"app {impl}: full sync, so it gets every indexer below")

    if not any(c["implementation"] == "Transmission" for c in api.get("/downloadclient")):
        schema = next(s for s in api.get("/downloadclient/schema") if s["implementation"] == "Transmission")
        client = fill(schema, host="transmission", port=9091, urlBase="/transmission/")
        client.update(name="Transmission", enable=True, priority=1)
        api.post("/downloadclient?forceSave=true", client)
        note("download client: Transmission (for grabs made in Prowlarr itself)")

    have = {i.get("definitionName") for i in api.get("/indexer")}
    todo = [(d, via) for d, via in PUBLIC_INDEXERS if d not in have]
    if todo:
        schemas = {s.get("definitionName"): s for s in api.get("/indexer/schema")}
        profile = api.get("/appprofile")[0]["id"]
        for definition, via_byparr in todo:
            schema = schemas.get(definition)
            if not schema:
                warn(f"indexer {definition}: no longer a Prowlarr definition — skipped")
                continue
            ix = json.loads(json.dumps(schema))
            ix.update(enable=True, appProfileId=profile, priority=25,
                      tags=[byparr_tag] if via_byparr else [])
            try:
                # forceSave: a tracker that is down today is still worth having.
                api.post("/indexer?forceSave=true", ix)
                note(f"indexer {schema['name']}" + (" (via Byparr)" if via_byparr else ""))
            except HttpError as e:
                warn(f"indexer {definition}: {e}")
        api.post("/command", {"name": "ApplicationIndexerSync"})
    else:
        note("public indexers exist")


