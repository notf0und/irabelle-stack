# --- configuration ----------------------------------------------------------
def read_env(stack):
    """KEY=value lines of <stack>/.env, the same way setup.sh's env_var reads them."""
    out = {}
    path = os.path.join(REPO, stack, ".env")
    try:
        with open(path) as fh:
            for line in fh:
                m = re.match(r"\s*([A-Za-z0-9_]+)\s*=\s*(.*)$", line)
                if m:
                    out[m.group(1)] = m.group(2).split("#", 1)[0].strip().strip("\"'")
    except OSError:
        pass
    return out


def set_env(stack, key, value):
    """Set KEY=value in <stack>/.env, replacing the line if it is there."""
    path = os.path.join(REPO, stack, ".env")
    with open(path) as fh:
        lines = fh.read().splitlines()
    for i, line in enumerate(lines):
        if re.match(rf"\s*{re.escape(key)}\s*=", line):
            lines[i] = f"{key}={value}"
            break
    else:
        lines.append(f"{key}={value}")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


