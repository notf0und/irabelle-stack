def ha_trust_traefik():
    """Newer HA keeps its HTTP settings in .storage/http, and imports the YAML
    http: block only once — onboarding creates the file before we could add
    one. So set the two keys there, with HA stopped (it rewrites the file on
    the way down). HA writes it root-only (0600), so it is read through the
    container and edited by a one-off one of the same image."""
    r = docker("exec", "homeassistant", "cat", "/config/.storage/http")
    if r.returncode != 0:
        return None                     # no such file: an HA that reads YAML
    stable = json.loads(r.stdout).get("data", {}).get("stable", {})
    if stable.get("use_x_forwarded_for") and set(HA_PROXIES) <= set(stable.get("trusted_proxies", [])):
        return False
    info = json.loads(docker("inspect", "homeassistant").stdout)[0]
    image = info["Config"]["Image"]
    config = next(m["Source"] for m in info["Mounts"] if m["Destination"] == "/config")
    docker("stop", "homeassistant", check=True)
    try:
        docker("run", "--rm", "--entrypoint", "python3", "-v", f"{config}:/config", image,
               "-c", HA_HTTP_EDIT, *HA_PROXIES, check=True)
    finally:
        docker("start", "homeassistant", check=True)
    return True


