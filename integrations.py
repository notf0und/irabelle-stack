def fill(schema_item, **values):
    """A copy of an *arr schema entry with the given fields set."""
    item = json.loads(json.dumps(schema_item))
    for f in item.get("fields", []):
        if f["name"] in values:
            f["value"] = values[f["name"]]
    return item


def field(item, name):
    for f in item.get("fields", []):
        if f["name"] == name:
            return f.get("value")
    return None


def quality_leaves(items):
    """Every leaf quality in a quality profile's item tree."""
    for item in items:
        if item.get("quality") is not None:
            yield item
        elif item.get("items"):
            yield from quality_leaves(item["items"])


